#!/usr/bin/env python3
"""Generate Go and browser data contracts from the canonical OpenAPI document."""
import argparse
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SCHEMAS = json.loads((ROOT / 'openapi.json').read_text())['components']['schemas']


def typescript(schema):
    if '$ref' in schema:
        return schema['$ref'].split('/')[-1]
    if 'enum' in schema:
        return ' | '.join(json.dumps(value) for value in schema['enum'])
    if 'anyOf' in schema:
        return ' | '.join(typescript(value) for value in schema['anyOf'])
    kind = schema.get('type')
    if kind == 'array':
        return 'Array<' + typescript(schema['items']) + '>'
    if kind == 'object':
        if 'properties' not in schema:
            return 'Record<string, ' + typescript(schema['additionalProperties']) + '>'
        required = schema.get('required', [])
        fields = [
            '  ' + key + ('' if key in required else '?') + ': ' + typescript(value) + ';'
            for key, value in schema['properties'].items()
        ]
        return '{\n' + '\n'.join(fields) + '\n}'
    return {'integer': 'number', 'number': 'number', 'boolean': 'boolean',
            'string': 'string', 'null': 'null'}[kind]


def go_name(name):
    words = re.sub(r'([a-z])([A-Z])', r'\1 \2', name).split()
    return ''.join(word.upper() if word.lower() in ('id', 'csrf') else word.title() for word in words)


def golang(schema):
    if '$ref' in schema:
        return schema['$ref'].split('/')[-1]
    if 'anyOf' in schema:
        nonnull = next(value for value in schema['anyOf'] if value.get('type') != 'null')
        return '*' + golang(nonnull)
    kind = schema.get('type')
    if kind == 'array':
        return '[]' + golang(schema['items'])
    if kind == 'object':
        if 'properties' not in schema:
            return 'map[string]' + golang(schema['additionalProperties'])
        required = schema.get('required', [])
        fields = []
        for key, value in schema['properties'].items():
            tag = key + ('' if key in required else ',omitempty')
            field_type = golang(value)
            if key not in required and '$ref' in value:
                field_type = '*' + field_type
            fields.append(' ' + go_name(key) + ' ' + field_type + ' `json:"' + tag + '"`')
        return 'struct {\n' + '\n'.join(fields) + '\n}'
    return {'integer': 'int64', 'number': 'float64', 'boolean': 'bool', 'string': 'string'}[kind]


ts_text = '// Generated by python3 packages/contracts/generate.py. Do not edit.\n\n'
ts_text += '\n\n'.join('export type ' + name + ' = ' + typescript(schema) + ';'
                        for name, schema in SCHEMAS.items()) + '\n'


go_text = '// Code generated by packages/contracts/generate.py; DO NOT EDIT.\npackage budget\n\n'
go_text += '\n\n'.join('// ' + name + ' is defined in the canonical OpenAPI contract.\ntype '
                        + name + ' ' + golang(schema) for name, schema in SCHEMAS.items()) + '\n'
gofmt = shutil.which('gofmt')
if gofmt is None:
    sys.exit('gofmt must be on PATH to generate Go contracts')
go_text = subprocess.run([gofmt], input=go_text, text=True, capture_output=True, check=True).stdout
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true', help='Fail if generated contracts differ')
arguments = parser.parse_args()
bundle = {'$schema': 'http://json-schema.org/draft-07/schema#', '$defs': SCHEMAS}
schema_text = json.dumps(bundle, indent=2).replace('#/components/schemas/', '#/$defs/') + '\n'
prettier = ROOT / '../../node_modules/.bin/prettier'
schema_text = subprocess.run(
    [str(prettier.resolve()), '--stdin-filepath', str(ROOT / 'schema.json')],
    input=schema_text, text=True, capture_output=True, check=True,
).stdout
outputs = {
    ROOT / 'schema.json': schema_text,
    ROOT / 'index.ts': ts_text,
    (ROOT / '../../apps/api/internal/budget/contracts.gen.go').resolve(): go_text,
}
for path, content in outputs.items():
    if arguments.check:
        if not path.exists() or path.read_text() != content:
            sys.exit(f'Generated contract differs: {path}. Run npm run contracts:generate.')
    else:
        path.write_text(content)
