import { lstat, readdir, readFile } from 'node:fs/promises';
import { extname, relative, resolve } from 'node:path';

const MAX_SOURCE_LINES = 300;
const SOURCE_EXTENSIONS = new Set([
  '.cjs',
  '.css',
  '.go',
  '.js',
  '.jsx',
  '.mjs',
  '.py',
  '.sh',
  '.sql',
  '.ts',
  '.tsx',
]);
const EXCLUDED_DIRECTORIES = new Set([
  '.git',
  '.next',
  '.turbo',
  '.vite',
  'build',
  'coverage',
  'dist',
  'node_modules',
  'vendor',
]);
const GENERATED_HEADER =
  /^(?:\/\/|#|\/\*|\*)\s*(?:Code generated\b.*DO NOT EDIT\.|Generated by\b.*Do not edit\.)/m;

/** Includes authored tests; skips only build/dependency directories and symbolic links. */
async function sourceFiles(path) {
  const info = await lstat(path);
  if (info.isSymbolicLink()) return [];
  if (info.isFile()) return SOURCE_EXTENSIONS.has(extname(path)) ? [path] : [];
  const entries = await readdir(path, { withFileTypes: true });
  const files = await Promise.all(
    entries.map((entry) => {
      if (entry.isSymbolicLink() || EXCLUDED_DIRECTORIES.has(entry.name)) return [];
      return sourceFiles(resolve(path, entry.name));
    }),
  );
  return files.flat();
}

/** Counts physical lines, including comments, so formatting cannot hide file growth. */
function physicalLines(source) {
  if (!source) return 0;
  return source.split('\n').length - (source.endsWith('\n') ? 1 : 0);
}

async function main() {
  const paths = process.argv.slice(2);
  const roots = paths.length ? paths : ['.'];
  const files = [
    ...new Set((await Promise.all(roots.map((path) => sourceFiles(resolve(path))))).flat()),
  ];
  let checked = 0;
  let failed = false;
  for (const file of files.sort()) {
    const source = await readFile(file, 'utf8');
    if (GENERATED_HEADER.test(source.split('\n').slice(0, 10).join('\n'))) continue;
    checked += 1;
    const lines = physicalLines(source);
    if (lines <= MAX_SOURCE_LINES) continue;
    console.error(
      `${relative(process.cwd(), file)}: ${lines} physical lines (maximum ${MAX_SOURCE_LINES})`,
    );
    failed = true;
  }
  if (failed) process.exitCode = 1;
  else
    console.log(
      `Source size passed: ${checked} authored files, maximum ${MAX_SOURCE_LINES} physical lines.`,
    );
}

await main().catch((error) => {
  console.error(`Source size check failed: ${error.message}`);
  process.exitCode = 1;
});
